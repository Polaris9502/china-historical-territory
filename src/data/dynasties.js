// 根据年份获取时期
export function getPeriodByYear(year) {
	for (let i = periods.length - 1; i >= 0; i--) {
		if (year >= periods[i].startYear) {
			return periods[i]
		}
	}
	return periods[0]
}

// 格式化年份
export function formatYear(year) {
	if (year < 0) {
		return `公元前${Math.abs(year)}年`
	}
	return `公元${year}年`
}

// 向后兼容
export const dynasties = periods
export function getDynastyByYear(year) {
	return getPeriodByYear(year)
}
